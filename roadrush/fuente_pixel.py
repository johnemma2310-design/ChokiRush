_ACENTO_AGUDO = {'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U'}


class FuentePixel:
    """Dibuja texto con glifos 5x7. Cachea cada glifo por (caracter, escala, color)."""

    ALTO = 7
    AVANCE = 6

    def __init__(self):
        self._cache = {}

    def ancho(self, texto, escala=1):
        n = len(str(texto))
        return 0 if n == 0 else n * self.AVANCE * escala - escala

    def _glifo(self, ch, escala, color):
        clave = (ch, escala, color)
        sup = self._cache.get(clave)
        if sup is not None:
            return sup
        sup = pygame.Surface((5 * escala, 9 * escala), pygame.SRCALPHA)
        base = _ACENTO_AGUDO.get(ch, {'Ü': 'U', 'Ñ': 'N'}.get(ch, ch))
        filas = GLIFOS.get(base, GLIFOS['?'])
        for fy, fila in enumerate(filas):
            for fx, c in enumerate(fila):
                if c == '#':
                    sup.fill(color, (fx * escala, (fy + 2) * escala, escala, escala))
        extra = ()
        if ch in _ACENTO_AGUDO:
            extra = ((3, 0), (2, 1))
        elif ch == 'Ü':
            extra = ((1, 1), (3, 1))
        elif ch == 'Ñ':
            extra = ((1, 1), (2, 0), (3, 1), (4, 0))
        for fx, fy in extra:
            sup.fill(color, (fx * escala, fy * escala, escala, escala))
        self._cache[clave] = sup
        return sup

    def _pintar(self, sup, texto, x, y, escala, color):
        paso = self.AVANCE * escala
        for i, ch in enumerate(texto):
            if ch != ' ':
                sup.blit(self._glifo(ch, escala, color), (x + i * paso, y - 2 * escala))

    def texto(self, sup, texto, x, y, escala=1, color=(245, 245, 245),
              sombra=(10, 10, 20), alinear='izq'):
        """Dibuja `texto` con la esquina superior en (x, y). Devuelve el Rect ocupado."""
        texto = str(texto).upper()
        w = self.ancho(texto, escala)
        if alinear == 'centro':
            x -= w // 2
        elif alinear == 'der':
            x -= w
        x, y = int(x), int(y)
        if sombra is not None:
            self._pintar(sup, texto, x + escala, y + escala, escala, tuple(sombra))
        self._pintar(sup, texto, x, y, escala, tuple(color))
        return pygame.Rect(x, y, w, self.ALTO * escala)


